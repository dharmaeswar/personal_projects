-- Snowflake DDL for the home-health data warehouse.
-- Mirrors the SQLite schema in homehealth/warehouse.py.
-- Run once per environment: snowsql -f 01_create_tables.sql

CREATE DATABASE IF NOT EXISTS HOME_HEALTH;
USE DATABASE HOME_HEALTH;
CREATE SCHEMA IF NOT EXISTS WH;

CREATE TABLE IF NOT EXISTS WH.DIM_PATIENT (
    PATIENT_SK NUMBER AUTOINCREMENT PRIMARY KEY,
    PATIENT_KEY VARCHAR NOT NULL,
    PATIENT_NAME VARCHAR NOT NULL,
    CARE_PLAN VARCHAR NOT NULL,
    VALID_FROM DATE NOT NULL,
    VALID_TO DATE,
    IS_CURRENT BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS WH.DIM_CLINICIAN (
    CLINICIAN_SK NUMBER AUTOINCREMENT PRIMARY KEY,
    CLINICIAN_ID VARCHAR NOT NULL UNIQUE,
    CLINICIAN_NAME VARCHAR NOT NULL DEFAULT 'Unknown'
);

CREATE TABLE IF NOT EXISTS WH.DIM_DATE (
    DATE_SK DATE PRIMARY KEY,
    VISIT_DATE DATE NOT NULL,
    YEAR NUMBER NOT NULL,
    MONTH NUMBER NOT NULL,
    DAY NUMBER NOT NULL
);

CREATE TABLE IF NOT EXISTS WH.FACT_HOME_VISIT (
    VISIT_ID VARCHAR PRIMARY KEY,
    PATIENT_SK NUMBER NOT NULL REFERENCES WH.DIM_PATIENT (PATIENT_SK),
    CLINICIAN_SK NUMBER NOT NULL REFERENCES WH.DIM_CLINICIAN (CLINICIAN_SK),
    DATE_SK DATE NOT NULL REFERENCES WH.DIM_DATE (DATE_SK),
    DURATION_MIN NUMBER NOT NULL,
    ASSESSMENT_SCORE NUMBER NOT NULL,
    SOURCE VARCHAR NOT NULL,
    SCHEMA_VERSION VARCHAR NOT NULL,
    LOADED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS WH.LOAD_LOG (
    LOAD_ID NUMBER AUTOINCREMENT PRIMARY KEY,
    RUN_ID VARCHAR NOT NULL,
    SOURCE_ROWS NUMBER NOT NULL,
    LOADED NUMBER NOT NULL,
    QUARANTINED NUMBER NOT NULL,
    LOADED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS WH.QUARANTINE (
    QUARANTINE_ID NUMBER AUTOINCREMENT PRIMARY KEY,
    RUN_ID VARCHAR NOT NULL,
    VISIT_ID VARCHAR,
    REASONS VARCHAR NOT NULL,
    LOADED_AT TIMESTAMP_NTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS WH.WATERMARK (
    ID NUMBER PRIMARY KEY,
    LAST_VISIT_DATE DATE
);
MERGE INTO WH.WATERMARK T
USING (SELECT 1 AS ID, NULL AS LAST_VISIT_DATE) S
ON T.ID = S.ID
WHEN NOT MATCHED THEN INSERT (ID, LAST_VISIT_DATE) VALUES (S.ID, S.LAST_VISIT_DATE);
