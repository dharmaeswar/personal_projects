"""Kubernetes cluster lifecycle management for the Platform Ops Automation demo.

Covers the work a container platform team does across the full lifecycle
of its clusters: upgrade readiness, safe node drains, and policy
enforcement in the shape of Kyverno / OPA Gatekeeper-style rules.

- Upgrade readiness: control-plane vs kubelet version skew follows the
  Kubernetes support policy (kubelet must not be newer than the API
  server, and may be at most 3 minor versions older); nodes must be
  Ready; workloads using removed APIs block the upgrade; a drain is
  only safe while every PodDisruptionBudget still leaves at least one
  replica running.
- Policy checks: every namespace needs a default-deny network policy,
  containers must not run as root, every container needs CPU/memory
  limits, and images must not use the `latest` tag.
- Capacity: per-namespace CPU/memory requests against allocatable
  capacity, with headroom and a scale-out hint.

Demo project. All cluster state here is synthetic input supplied by
the caller or generated by `generate_synthetic_cluster`; no real
cluster is contacted and no production Kubernetes operations
experience is claimed.
"""

import re

# Kubernetes supports kubelet up to 3 minor versions behind the API server.
MAX_MINOR_SKEW = 3

_VERSION_RE = re.compile(r"^v?(?P<major>\d+)\.(?P<minor>\d+)(?:\.(?P<patch>\d+))?$")


def parse_version(version):
    """Parse a Kubernetes version string like 'v1.31.2' into (major, minor, patch).

    Returns None when the string is not a version. Patch defaults to 0.
    """
    if not isinstance(version, str):
        return None
    match = _VERSION_RE.match(version.strip())
    if not match:
        return None
    return (
        int(match.group("major")),
        int(match.group("minor")),
        int(match.group("patch") or 0),
    )


def version_skew_ok(control_plane, kubelet):
    """Check kubelet version skew against the control plane.

    Returns {"ok": bool, "reason": str}. The kubelet must not be newer
    than the API server and may be at most MAX_MINOR_SKEW minor versions
    older. Patch differences never block.
    """
    control = parse_version(control_plane)
    node = parse_version(kubelet)
    if control is None or node is None:
        return {"ok": False, "reason": f"unparsable version: {control_plane} / {kubelet}"}
    if node[0] != control[0]:
        return {"ok": False, "reason": f"major version mismatch: {control_plane} vs {kubelet}"}
    if node[1] > control[1]:
        return {
            "ok": False,
            "reason": f"kubelet {kubelet} is newer than control plane {control_plane}",
        }
    if control[1] - node[1] > MAX_MINOR_SKEW:
        return {
            "ok": False,
            "reason": f"kubelet {kubelet} is {control[1] - node[1]} minor versions behind {control_plane} (max {MAX_MINOR_SKEW})",
        }
    return {"ok": True, "reason": f"skew ok: {control_plane} vs {kubelet}"}


def drain_is_safe(replicas, min_available, draining=1):
    """Check whether draining `draining` nodes keeps a workload available.

    Safe when replicas minus draining nodes still leaves at least
    min_available pods running. Returns {"safe": bool, "reason": str}.
    """
    remaining = replicas - draining
    if remaining >= min_available:
        return {
            "safe": True,
            "reason": f"{remaining} of {replicas} replicas stay up (minAvailable {min_available})",
        }
    return {
        "safe": False,
        "reason": f"only {remaining} of {replicas} replicas stay up, below minAvailable {min_available}",
    }


def check_upgrade_readiness(cluster):
    """Check whether a cluster is ready for a control-plane upgrade.

    `cluster` is a dict with:
        control_plane_version: str, e.g. "v1.31.2"
        nodes: [{name, version, ready: bool}]
        workloads: [{name, namespace, replicas, min_available, uses_removed_api: bool}]
        target_version: str, the version being upgraded to

    Returns {"ready": bool, "blockers": [str], "warnings": [str]}.
    """
    blockers = []
    warnings = []
    target = cluster.get("target_version")
    if parse_version(target) is None:
        blockers.append(f"target version {target!r} is not a valid version")
    for node in cluster.get("nodes") or []:
        if not node.get("ready"):
            blockers.append(f"node {node.get('name')} is not Ready")
        skew = version_skew_ok(cluster.get("control_plane_version"), node.get("version"))
        if not skew["ok"]:
            blockers.append(f"node {node.get('name')}: {skew['reason']}")
    for workload in cluster.get("workloads") or []:
        if workload.get("uses_removed_api"):
            blockers.append(
                f"workload {workload.get('namespace')}/{workload.get('name')} uses an API removed in {target}"
            )
        drain = drain_is_safe(
            workload.get("replicas", 0), workload.get("min_available", 1)
        )
        if not drain["safe"]:
            warnings.append(
                f"workload {workload.get('namespace')}/{workload.get('name')}: drain unsafe — {drain['reason']}"
            )
    return {"ready": not blockers, "blockers": blockers, "warnings": warnings}


def check_pod_policy(pod):
    """Apply Kyverno/OPA-style policy rules to one pod spec.

    `pod` is a dict with namespace, name, containers: [{name, image,
    run_as_root: bool, resources: {limits: {...}}}], and
    default_deny_policy: bool for its namespace.

    Returns a list of violation dicts {rule, detail}. Empty means compliant.
    """
    violations = []
    if not pod.get("default_deny_policy"):
        violations.append(
            {
                "rule": "default-deny-network-policy",
                "detail": f"namespace {pod.get('namespace')} has no default-deny NetworkPolicy",
            }
        )
    for container in pod.get("containers") or []:
        name = container.get("name")
        if container.get("run_as_root"):
            violations.append(
                {
                    "rule": "no-root-user",
                    "detail": f"container {name} runs as root",
                }
            )
        limits = (container.get("resources") or {}).get("limits") or {}
        if not limits.get("cpu") or not limits.get("memory"):
            violations.append(
                {
                    "rule": "resource-limits-required",
                    "detail": f"container {name} is missing cpu/memory limits",
                }
            )
        image = container.get("image") or ""
        if image.endswith(":latest") or ":" not in image:
            violations.append(
                {
                    "rule": "no-latest-tag",
                    "detail": f"container {name} uses unpinned image {image!r}",
                }
            )
    return violations


def check_namespace_policies(pods):
    """Run policy checks over a list of pod specs.

    Returns {"violations": {pod_name: [violations]}, "compliant": bool}.
    """
    violations = {}
    for pod in pods:
        found = check_pod_policy(pod)
        if found:
            violations[pod.get("name")] = found
    return {"violations": violations, "compliant": not violations}


def parse_cpu(value):
    """Parse a Kubernetes CPU quantity ('100m', '2', '0.5') into millicores."""
    if value is None:
        return 0.0
    text = str(value).strip()
    if text.endswith("m"):
        return float(text[:-1])
    return float(text) * 1000


def parse_memory(value):
    """Parse a Kubernetes memory quantity ('128Mi', '1Gi', '512M') into MiB."""
    if value is None:
        return 0.0
    text = str(value).strip()
    multipliers = {"Ki": 1 / 1024, "Mi": 1, "Gi": 1024, "Ti": 1024 * 1024,
                   "K": 1 / 1024, "M": 1, "G": 1024}
    for suffix, factor in multipliers.items():
        if text.endswith(suffix):
            return float(text[: -len(suffix)]) * factor
    return float(text) / (1024 * 1024)


def namespace_capacity(namespaces, allocatable):
    """Compare per-namespace CPU/memory requests with cluster capacity.

    `namespaces` is a list of {name, cpu_requests, memory_requests}
    (quantities as strings, e.g. '2500m' / '8Gi'). `allocatable` is a
    dict {cpu, memory} for the whole cluster.

    Returns a report dict with per-namespace usage and headroom, plus
    totals and a scale-out hint when headroom drops below 20%.
    """
    total_cpu = parse_cpu(allocatable.get("cpu"))
    total_mem = parse_memory(allocatable.get("memory"))
    rows = []
    used_cpu = 0.0
    used_mem = 0.0
    for namespace in namespaces:
        cpu = parse_cpu(namespace.get("cpu_requests"))
        mem = parse_memory(namespace.get("memory_requests"))
        used_cpu += cpu
        used_mem += mem
        rows.append(
            {
                "namespace": namespace.get("name"),
                "cpu_m": cpu,
                "cpu_pct": (cpu / total_cpu * 100) if total_cpu else 0.0,
                "memory_mib": mem,
                "memory_pct": (mem / total_mem * 100) if total_mem else 0.0,
            }
        )
    cpu_headroom = 100 - (used_cpu / total_cpu * 100) if total_cpu else 0.0
    mem_headroom = 100 - (used_mem / total_mem * 100) if total_mem else 0.0
    return {
        "namespaces": rows,
        "total_cpu_m": used_cpu,
        "total_memory_mib": used_mem,
        "cpu_headroom_pct": round(cpu_headroom, 1),
        "memory_headroom_pct": round(mem_headroom, 1),
        "scale_out": cpu_headroom < 20 or mem_headroom < 20,
    }


def summarize_upgrade(report):
    """One-line human summary of an upgrade-readiness report."""
    if report["ready"] and not report["warnings"]:
        return "ready to upgrade: no blockers, no warnings"
    parts = []
    if report["blockers"]:
        parts.append(f"{len(report['blockers'])} blocker(s)")
    if report["warnings"]:
        parts.append(f"{len(report['warnings'])} warning(s)")
    return "not ready: " + "; ".join(parts) if report["blockers"] else "ready with warnings: " + "; ".join(parts)


def generate_synthetic_cluster(seed=11):
    """Generate a small synthetic cluster for demos.

    Control plane v1.31.2, three nodes (one 3 minor versions behind,
    one not Ready), and two workloads — one using a removed API, one
    with a drain-unsafe PodDisruptionBudget. Returns the cluster dict.
    """
    return {
        "control_plane_version": "v1.31.2",
        "target_version": "v1.32.0",
        "nodes": [
            {"name": "node-a", "version": "v1.31.1", "ready": True},
            {"name": "node-b", "version": "v1.28.0", "ready": True},
            {"name": "node-c", "version": "v1.31.2", "ready": False},
        ],
        "workloads": [
            {
                "name": "platform-ops",
                "namespace": "default",
                "replicas": 3,
                "min_available": 2,
                "uses_removed_api": True,
            },
            {
                "name": "batch-worker",
                "namespace": "batch",
                "replicas": 2,
                "min_available": 2,
                "uses_removed_api": False,
            },
        ],
    }


def main():
    cluster = generate_synthetic_cluster()
    report = check_upgrade_readiness(cluster)
    print(summarize_upgrade(report))
    for blocker in report["blockers"]:
        print("  blocker:", blocker)
    for warning in report["warnings"]:
        print("  warning:", warning)
    pods = [
        {
            "name": "platform-ops",
            "namespace": "default",
            "default_deny_policy": True,
            "containers": [
                {
                    "name": "web",
                    "image": "platform-ops:v1.4.0",
                    "run_as_root": False,
                    "resources": {"limits": {"cpu": "500m", "memory": "512Mi"}},
                }
            ],
        }
    ]
    policy = check_namespace_policies(pods)
    print("policy compliant:", policy["compliant"])
    capacity = namespace_capacity(
        [
            {"name": "default", "cpu_requests": "2500m", "memory_requests": "8Gi"},
            {"name": "batch", "cpu_requests": "1500m", "memory_requests": "4Gi"},
        ],
        {"cpu": "8000m", "memory": "32Gi"},
    )
    print(
        "capacity headroom: cpu",
        f"{capacity['cpu_headroom_pct']}%",
        "memory",
        f"{capacity['memory_headroom_pct']}%",
        "scale out:",
        capacity["scale_out"],
    )


if __name__ == "__main__":
    main()
