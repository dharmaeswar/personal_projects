"""GitOps drift detection and rollout gates for the Platform Ops Automation demo.

Compares the desired state declared in Kubernetes manifests (the `k8s/`
directory of this project) with a snapshot of live cluster state, and
reports drift: image tags, replica counts, environment variables, and
resource limits that no longer match what Git says should be running.
A rollout gate blocks a deploy while drift is unresolved or while the
error-budget burn is too high.

Also includes small W3C `traceparent` helpers (the propagation format
OpenTelemetry uses) so a service can pass trace context between the
backend service and the tooling that calls it.

Demo project. All live state here is synthetic input supplied by the
caller or generated by `generate_synthetic_state`; no real cluster is
contacted and no production GitOps or observability deployment is
claimed.
"""

import random
import re

TRACEPARENT_RE = re.compile(
    r"^00-(?P<trace_id>[0-9a-f]{32})-(?P<parent_id>[0-9a-f]{16})-(?P<flags>[0-9a-f]{2})$"
)

# Fields compared inside a container spec, in drift-report order.
_CONTAINER_FIELDS = ("image", "replicas", "env", "resources")


def resource_key(resource):
    """Stable identity for a manifest/live resource: (kind, namespace, name)."""
    metadata = resource.get("metadata") or {}
    return (
        resource.get("kind"),
        metadata.get("namespace", "default"),
        metadata.get("name"),
    )


def desired_state(manifests):
    """Index a list of parsed manifest dicts by resource key.

    Manifests with no kind or no metadata name are skipped.
    """
    state = {}
    for manifest in manifests:
        if not isinstance(manifest, dict):
            continue
        key = resource_key(manifest)
        if key[0] is None or key[2] is None:
            continue
        state[key] = manifest
    return state


def _container_map(resource):
    """Map container name -> container spec for a workload resource."""
    spec = (resource.get("spec") or {}).get("template", {}).get("spec", {})
    containers = spec.get("containers") or []
    return {c.get("name"): c for c in containers if isinstance(c, dict)}


def _env_map(container):
    env = container.get("env") or []
    return {e.get("name"): e.get("value") for e in env if isinstance(e, dict)}


def diff_container(desired, live):
    """Compare one desired container spec with its live counterpart.

    Returns a list of drift dicts: {field, desired, live}. Empty when
    the container matches.
    """
    drift = []
    if desired.get("image") != live.get("image"):
        drift.append(
            {"field": "image", "desired": desired.get("image"), "live": live.get("image")}
        )
    if _env_map(desired) != _env_map(live):
        drift.append(
            {"field": "env", "desired": _env_map(desired), "live": _env_map(live)}
        )
    if desired.get("resources") != live.get("resources"):
        drift.append(
            {
                "field": "resources",
                "desired": desired.get("resources"),
                "live": live.get("resources"),
            }
        )
    return drift


def diff_resource(desired, live):
    """Compare one desired resource with its live state.

    Returns a list of drift dicts, each with {field, desired, live}.
    Replica drift is reported on the workload spec; container drift is
    reported per container.
    """
    drift = []
    desired_replicas = (desired.get("spec") or {}).get("replicas")
    live_replicas = (live.get("spec") or {}).get("replicas")
    if desired_replicas is not None and desired_replicas != live_replicas:
        drift.append(
            {"field": "replicas", "desired": desired_replicas, "live": live_replicas}
        )
    desired_containers = _container_map(desired)
    live_containers = _container_map(live)
    for name, desired_container in desired_containers.items():
        live_container = live_containers.get(name)
        if live_container is None:
            drift.append(
                {"field": "container", "desired": name, "live": None}
            )
            continue
        for entry in diff_container(desired_container, live_container):
            entry["container"] = name
            drift.append(entry)
    for name in live_containers:
        if name not in desired_containers:
            drift.append({"field": "container", "desired": None, "live": name})
    return drift


def detect_drift(desired, live):
    """Compare full desired and live state dicts (keyed by resource_key).

    Returns a report dict:
        {"drifted": {key: [drift entries]}, "missing": [keys only in desired],
         "extra": [keys only in live], "in_sync": bool}
    """
    drifted = {}
    for key, desired_resource in desired.items():
        live_resource = live.get(key)
        if live_resource is None:
            continue
        entries = diff_resource(desired_resource, live_resource)
        if entries:
            drifted[key] = entries
    missing = [key for key in desired if key not in live]
    extra = [key for key in live if key not in desired]
    return {
        "drifted": drifted,
        "missing": missing,
        "extra": extra,
        "in_sync": not drifted and not missing and not extra,
    }


def summarize_drift(report):
    """One-line human summary of a drift report."""
    if report["in_sync"]:
        return "in sync: live state matches desired state"
    parts = []
    if report["drifted"]:
        parts.append(f"{len(report['drifted'])} resource(s) drifted")
    if report["missing"]:
        parts.append(f"{len(report['missing'])} resource(s) missing from live state")
    if report["extra"]:
        parts.append(f"{len(report['extra'])} extra resource(s) in live state")
    return "drift detected: " + "; ".join(parts)


def rollout_gate(report, error_budget_burn=0.0, max_burn=1.0):
    """Decide whether a rollout may proceed.

    Returns {"allowed": bool, "reasons": [str]}. Blocked when drift is
    unresolved or when error-budget burn exceeds `max_burn` (burn of
    1.0 means the budget is fully consumed).
    """
    reasons = []
    if not report["in_sync"]:
        reasons.append(summarize_drift(report))
    if error_budget_burn > max_burn:
        reasons.append(
            f"error-budget burn {error_budget_burn:.2f} exceeds limit {max_burn:.2f}"
        )
    return {"allowed": not reasons, "reasons": reasons}


def parse_traceparent(header):
    """Parse a W3C traceparent header.

    Returns {"trace_id", "parent_id", "sampled"} or None when the header
    is malformed. All-zero trace or parent ids are rejected.
    """
    if not isinstance(header, str):
        return None
    match = TRACEPARENT_RE.match(header.strip())
    if not match:
        return None
    trace_id = match.group("trace_id")
    parent_id = match.group("parent_id")
    flags = match.group("flags")
    if trace_id == "0" * 32 or parent_id == "0" * 16:
        return None
    if flags not in ("00", "01"):
        return None
    return {
        "trace_id": trace_id,
        "parent_id": parent_id,
        "sampled": flags == "01",
    }


def format_traceparent(trace_id, span_id, sampled=True):
    """Format a W3C traceparent header from ids.

    Raises ValueError for malformed ids.
    """
    if not re.fullmatch(r"[0-9a-f]{32}", trace_id or ""):
        raise ValueError("trace_id must be 32 lowercase hex chars")
    if not re.fullmatch(r"[0-9a-f]{16}", span_id or ""):
        raise ValueError("span_id must be 16 lowercase hex chars")
    if trace_id == "0" * 32 or span_id == "0" * 16:
        raise ValueError("trace_id and span_id must not be all zeros")
    return f"00-{trace_id}-{span_id}-{'01' if sampled else '00'}"


def generate_synthetic_state(seed=7):
    """Generate a small synthetic desired/live state pair for demos.

    The live state drifts in exactly one place: the web Deployment runs
    image tag `v1.4.1` while Git declares `v1.4.0`. Returns
    (desired, live) state dicts keyed by resource_key.
    """
    rng = random.Random(seed)
    base = {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": "platform-ops", "namespace": "default"},
        "spec": {
            "replicas": 3,
            "template": {
                "spec": {
                    "containers": [
                        {
                            "name": "web",
                            "image": "platform-ops:v1.4.0",
                            "env": [{"name": "PORT", "value": "8080"}],
                            "resources": {
                                "requests": {"cpu": "100m", "memory": "128Mi"},
                                "limits": {"cpu": "500m", "memory": "512Mi"},
                            },
                        }
                    ]
                }
            },
        },
    }
    live = dict(base)
    live["spec"] = dict(base["spec"])
    live["spec"]["template"] = dict(base["spec"]["template"])
    live["spec"]["template"]["spec"] = dict(base["spec"]["template"]["spec"])
    live_container = dict(base["spec"]["template"]["spec"]["containers"][0])
    live_container["image"] = "platform-ops:v1.4.1"
    live["spec"]["template"]["spec"]["containers"] = [live_container]
    desired = desired_state([base])
    live_state = desired_state([live])
    rng.random()  # seed consumed so the helper stays deterministic per seed
    return desired, live_state


def main():
    desired, live = generate_synthetic_state()
    report = detect_drift(desired, live)
    print(summarize_drift(report))
    for key, entries in report["drifted"].items():
        print(f"{key}:")
        for entry in entries:
            print(f"  {entry['field']}: desired={entry['desired']} live={entry['live']}")
    gate = rollout_gate(report)
    print("rollout allowed:", gate["allowed"])
    print("reasons:", gate["reasons"] or ["none"])
    header = format_traceparent("4bf92f3577b34da6a3ce929d0e0e4736", "00f067aa0ba902b7")
    print("traceparent:", header, "->", parse_traceparent(header))


if __name__ == "__main__":
    main()
