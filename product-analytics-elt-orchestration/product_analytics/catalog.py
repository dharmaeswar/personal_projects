"""Dataset catalog: generated docs so teams can find and trust the data.

``generate`` writes a Markdown catalog listing every table (with row
counts), every metric definition, and the latest quality results. It is
regenerated by the DAG's publish step, so the docs always match the
warehouse that actually ran — discoverability without a separate wiki
that drifts out of date.
"""
from __future__ import annotations

import sqlite3

from .metrics import DEFINITIONS


def generate(conn: sqlite3.Connection, path: str) -> str:
    lines = ["# Product Analytics Catalog\n"]
    lines.append("Generated by the pipeline publish step. Tables, metrics and")
    lines.append("quality results below always describe the warehouse that ran.\n")
    lines.append("## Tables\n")
    tables = conn.execute(
        "SELECT name FROM sqlite_master WHERE type IN ('table', 'view') "
        "AND name NOT LIKE 'sqlite_%' ORDER BY name"
    ).fetchall()
    for (name,) in tables:
        try:
            count = conn.execute(f"SELECT COUNT(*) FROM {name}").fetchone()[0]
        except sqlite3.Error:
            count = -1
        lines.append(f"- `{name}` — {count} rows")
    lines.append("\n## Metrics (definitions as code)\n")
    for name, meta in DEFINITIONS.items():
        lines.append(f"- **{name}** — {meta['definition']}")
    lines.append("\n## Latest data-quality results\n")
    for row in conn.execute(
        "SELECT check_name, status, detail FROM quality_results ORDER BY check_name"
    ):
        lines.append(f"- {row['check_name']}: {row['status']} — {row['detail']}")
    text = "\n".join(lines) + "\n"
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return text
